<p class="lede">Documenting energy code compliance for an air handler means collecting the right equipment data, entering it into the jurisdiction's compliance tool or forms, and keeping that data consistent from permit drawings through submittals and inspection. The steps below apply whether you use COMcheck, California's NRCC forms or an NECB compliance report.</p>

<h2>Step 1: Confirm the path and the tool</h2>
<ol>
<li>Identify the adopted energy code and edition with the authority having jurisdiction.</li>
<li>Decide on the compliance path: prescriptive, trade-off, or whole-building performance modelling.</li>
<li>Identify the required documentation format:
<ul>
<li>Many US jurisdictions accept COMcheck reports, generated with the free US DOE software, for IECC and 90.1.</li>
<li>California requires Title 24 Certificate of Compliance forms, generated through approved software and often registered with a data registry.</li>
<li>Canadian jurisdictions using NECB may require a prescriptive compliance report, a trade-off calculation or an energy model report, sometimes on provincial or municipal forms.</li>
<li>Performance paths require energy model output reports with the inputs listed.</li>
</ul></li>
<li>Confirm who must sign: the mechanical engineer of record in most jurisdictions.</li>
</ol>
<p class="note">This guide explains how to document, not what the code requires. For the content of the requirements, see guides such as <a href="<?= url('guides/ashrae-90-1-fan-power-limitation') ?>">90.1 fan power limitation</a> and <a href="<?= url('guides/necb-vs-ashrae-90-1') ?>">NECB vs ASHRAE 90.1</a>.</p>

<h2>Step 2: Gather AHU data</h2>
<p>Build a data sheet for each air handler before opening the tool. Missing data is the most common cause of incomplete forms.</p>
<table>
<thead><tr><th>Data item</th><th>Where it comes from</th></tr></thead>
<tbody>
<tr><td>Design supply, return, outdoor and exhaust airflow</td><td>Equipment schedule, ventilation calculation</td></tr>
<tr><td>Fan type, motor nameplate hp, bhp or input kW at design</td><td>Fan selection report</td></tr>
<tr><td>Fan Energy Index at design point</td><td>Fan selection report, AMCA certification</td></tr>
<tr><td>Fan speed control type (VFD, EC, constant)</td><td>Schedule, controls design</td></tr>
<tr><td>Pressure drop devices claimed for fan power credits</td><td>AHU selection report</td></tr>
<tr><td>Cooling and heating capacity, source and efficiency</td><td>Coil selections, plant schedules</td></tr>
<tr><td>Economizer type, high-limit control, damper leakage</td><td>Controls design, damper submittal</td></tr>
<tr><td>Energy recovery type, effectiveness, bypass</td><td>Recovery device selection, AHRI 1060 data</td></tr>
<tr><td>Control features: resets, DCV, setback, shutoff</td><td>Sequence of operation</td></tr>
<tr><td>Motor efficiency</td><td>Motor data sheet</td></tr>
</tbody>
</table>

<h2>Step 3: Enter the mechanical systems</h2>
<ol>
<li>Create each HVAC system in the tool with its type (VAV, constant volume, DOAS, single-zone) since the tool applies different rules by type.</li>
<li>Link each air handler to its heating and cooling sources.</li>
<li>Enter fan data. In COMcheck, the fan power section asks for supply, return and exhaust fan data and calculates compliance with the allowance; enter pressure drop credits only for devices actually present.</li>
<li>Enter economizer data or select the exception that applies.</li>
<li>Enter energy recovery data or the exception that applies.</li>
<li>Answer the mandatory requirement checklists generated by the tool. Each item must be marked complies, does not apply, or is addressed elsewhere, with a drawing reference.</li>
</ol>
<p class="warn">Tools accept whatever you type. Entering a fan bhp from an early selection, then changing the fan, leaves a compliance report that no longer describes the building. Track the version of each selection used.</p>

<h2>Step 4: Cross-reference the drawings</h2>
<p>Plan reviewers compare forms to drawings. Make the link explicit:</p>
<ul>
<li>Put the key values on the mechanical schedules: fan bhp or kW, FEI, motor efficiency, recovery effectiveness, economizer type.</li>
<li>Include the sequence of operation showing required controls (supply air reset, static pressure reset, DCV, shutoff).</li>
<li>Reference compliance form section numbers or tool requirement IDs on the drawings where the jurisdiction expects it.</li>
<li>Include a general note stating the code and edition used.</li>
</ul>

<h2>Step 5: Handle performance-path documentation</h2>
<p>When the project uses modelling (Appendix G of 90.1, the Energy Cost Budget method, NECB performance path or California CBECC), the AHU documentation becomes model inputs:</p>
<ol>
<li>Report fan power for the proposed design from actual selections, not defaults.</li>
<li>Document part-load fan curves used in the model, and that they match the control method.</li>
<li>List energy recovery effectiveness at the conditions the model uses.</li>
<li>Show that mandatory requirements are met; modelling does not waive them.</li>
<li>Keep the model input report consistent with the equipment schedules.</li>
</ol>

<h2>Step 6: Maintain compliance through submittals</h2>
<ol>
<li>When the submittal arrives, compare the submitted fan power, FEI, recovery effectiveness and economizer data to the compliance report.</li>
<li>If any value is worse than the compliance documents, either reject the submittal or update and resubmit the compliance report to the AHJ.</li>
<li>Record the comparison in the submittal review response.</li>
</ol>
<p>The code items to check at submittal stage are covered in <a href="<?= url('guides/code-compliance-submittal-checklist') ?>">the code compliance checklist for AHU submittals</a>.</p>

<h2>Common documentation errors</h2>
<ul>
<li><strong>Nameplate versus brake horsepower.</strong> Entering motor nameplate horsepower where the tool expects bhp, or the reverse, can flip a pass to a fail.</li>
<li><strong>Missing return or exhaust fans.</strong> Fans that operate with the system must be included in the fan power calculation.</li>
<li><strong>Claiming credits for absent devices.</strong> A filter credit for a MERV class not actually specified will be caught at plan review.</li>
<li><strong>Exceptions without citations.</strong> Writing "economizer not required" without naming the exception invites a correction notice.</li>
<li><strong>Unit conversion slips</strong> on Canadian projects that mix L/s and cfm, or W and hp.</li>
</ul>

<h2>Step 7: Close out at inspection</h2>
<ul>
<li>Provide the inspector with the final compliance report and any installation or acceptance certificates required.</li>
<li>Have the as-built nameplate data available, since inspectors may compare motor horsepower and efficiency on site.</li>
<li>For jurisdictions requiring functional testing (for example California acceptance tests), complete and sign the required forms before final inspection.</li>
<li>Include compliance documents in the turnover package so future renovations know the original basis.</li>
</ul>
