<p class="lede">A food plant air handler may be hosed down, foamed with caustic or chlorinated sanitizers, and expected to drain dry with nothing left behind to grow bacteria. This checklist covers the stainless construction, drainage and sanitary design features to confirm before an AHU is approved for washdown service.</p>

<h2>Define the washdown regime first</h2>
<ul>
<li>[ ] Cleaning method documented with the plant sanitation team: dry clean, low-pressure rinse, high-pressure washdown, foam and rinse, or clean-in-place.</li>
<li>[ ] Cleaning chemicals listed with concentration and temperature (for example, chlorinated alkaline, quaternary ammonium, peracetic acid). These determine material compatibility.</li>
<li>[ ] Cleaning frequency and which sections are washed (coil sections only, or the whole unit).</li>
<li>[ ] Food safety program requirements identified (HACCP plan, customer audit standards, and applicable regulatory guidance). Note which hygienic design guidelines the owner follows.</li>
<li>[ ] Room classification for the spaces served: raw, ready-to-eat, high-care or packaging. Higher-risk zones drive higher filtration and pressure requirements.</li>
</ul>

<h2>Casing materials and construction</h2>
<ul>
<li>[ ] Interior surfaces in contact with air and wash water in stainless steel; 304 is typical, 316 where chlorides or aggressive sanitizers are used.</li>
<li>[ ] Exterior skin material agreed: stainless for washdown rooms; painted or galvanized acceptable for units in dry mechanical rooms.</li>
<li>[ ] Double-wall panels with fully enclosed insulation; no exposed insulation anywhere in the airstream.</li>
<li>[ ] Panel joints continuously welded or sealed with food-grade sealant; no open seams or lap joints where water and debris can collect.</li>
<li>[ ] Smooth interior finish, with a surface roughness agreed with the owner; no rough welds, burrs or crevices.</li>
<li>[ ] Coved or radiused interior corners where practical, to aid cleaning.</li>
<li>[ ] No horizontal ledges or interior stiffeners that trap water; any internal members sloped or closed.</li>
<li>[ ] Thermal break panels to prevent exterior condensation in cold rooms.</li>
<li>[ ] Fasteners in stainless; no exposed threads in the airstream where possible.</li>
</ul>
<p>General casing materials are compared in <a href="<?= url('guides/casing-materials-galvanized-stainless-aluminum') ?>">casing materials: galvanized, stainless and aluminum</a>; this checklist focuses on what food washdown adds.</p>

<h2>Floors and drainage</h2>
<ul>
<li>[ ] Welded, watertight stainless floor throughout washable sections, not just under coils.</li>
<li>[ ] Floor sloped to drain in at least one direction toward a low point, so no water remains after wash.</li>
<li>[ ] Drain connections at each low point in every washable section, sized for wash water flow, not just condensate.</li>
<li>[ ] Drains trapped appropriately for section static pressure, and arranged so traps can be cleaned and do not dry out between washes.</li>
<li>[ ] Drain pans under cooling coils sloped in two planes, fully drainable, and extended downstream far enough to catch carryover.</li>
<li>[ ] Raised base or curb so the floor can drain without water pooling around penetrations.</li>
<li>[ ] Floor penetrations sealed and minimized; no bolts protruding upward into the airstream.</li>
</ul>
<p>The design requirements for condensate drain pans are covered in <a href="<?= url('guides/drainable-welded-ahu-floors') ?>">drainable welded AHU floors</a>.</p>

<h2>Access and cleanability</h2>
<ul>
<li>[ ] Access doors to every section, large enough to clean all surfaces, with hinges and latches in stainless.</li>
<li>[ ] Door gaskets of food-compatible material, resistant to the specified chemicals and removable for cleaning or replacement.</li>
<li>[ ] Viewing windows in fan and coil sections, if requested.</li>
<li>[ ] Interior lights rated for washdown (wet location rating) with sealed fixtures.</li>
<li>[ ] Access sections between components long enough for a person with cleaning equipment.</li>
<li>[ ] No dead spaces behind components that cannot be reached or seen.</li>
</ul>

<h2>Components</h2>
<ul>
<li>[ ] Coils with stainless casings and headers, and fin spacing wide enough to clean (fewer fins per inch than typical commercial coils). Coated or stainless fins if required by chemistry.</li>
<li>[ ] Coils removable or cleanable from both faces.</li>
<li>[ ] Fans selected for washdown: direct-drive plenum fans with motors rated for washdown, or motors outside the airstream. Fan arrays simplify cleaning access.</li>
<li>[ ] Motors with washdown-duty enclosures where located in washed sections; electrical connections sealed.</li>
<li>[ ] Filters in frames that can be removed and washed, with gaskets; final filters per room classification.</li>
<li>[ ] Dampers in stainless with sealed bearings.</li>
<li>[ ] Humidifiers, if any, designed for hygiene and drainability.</li>
<li>[ ] Sensors with stainless or food-compatible housings and IP ratings suited to washdown.</li>
</ul>

<h2>Electrical and controls</h2>
<ul>
<li>[ ] Electrical enclosures rated for washdown, such as NEMA 4X, mounted outside the airstream.</li>
<li>[ ] Conduit and cable entries sealed; no conduit routes that drain water into enclosures.</li>
<li>[ ] VFDs located outside washdown zones, or in rated enclosures.</li>
<li>[ ] Control sequence for wash mode: fans off or at reduced speed, coils protected, heaters disabled, and a dry-out cycle after washing.</li>
</ul>
<p class="warn">Never energize electric heaters or run fans at full speed with wet internal surfaces unless the sequence and components are designed for it. A dry-out cycle with controlled airflow and moderate heat is safer.</p>

<h2>Pressurization and airflow</h2>
<ul>
<li>[ ] Room pressure cascade defined, with high-care and ready-to-eat zones positive to raw and general areas.</li>
<li>[ ] Supply airflow sized for room pressurization, process heat loads and condensation control.</li>
<li>[ ] Supply air dew point low enough to prevent condensation on cold surfaces in the processing room.</li>
<li>[ ] Outdoor air intakes away from waste handling, rendering and wastewater areas.</li>
</ul>

<h2>Documentation and testing</h2>
<ul>
<li>[ ] Material certificates for stainless, with grade.</li>
<li>[ ] Weld procedures and inspection standards.</li>
<li>[ ] Water test of floors and drain pans at the factory to confirm drainage and watertightness.</li>
<li>[ ] Factory run test and, if requested, witness inspection of hygienic details.</li>
<li>[ ] Cleaning and sanitation instructions in the O&amp;M manual, including chemical compatibility.</li>
</ul>
