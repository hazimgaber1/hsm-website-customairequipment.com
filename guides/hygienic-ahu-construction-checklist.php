<p class="lede">A hygienic air handler has interior surfaces that are smooth, non-porous and corrosion-resistant, with no crevices, exposed insulation or standing water, and with every surface reachable for cleaning and disinfection. Use the checklist below for hospitals, pharmaceutical and food facilities, labs and any project that cites a hygiene standard such as VDI 6022.</p>

<h2>What "hygienic" construction means</h2>
<p>Microorganisms need moisture, nutrients and somewhere to settle. In an AHU, nutrients arrive as dust, moisture comes from coils and humidifiers, and settling places are seams, crevices, porous materials and corners that are hard to clean. Hygienic construction removes those places and makes the remaining surfaces easy to inspect and clean. The German guideline VDI 6022 is widely referenced for hygiene requirements in air handling equipment, and EN 13053 also addresses hygiene features; owner standards in North American healthcare often draw on them alongside ASHRAE 62.1 and ASHRAE 170. Filtration is a separate topic and is not covered here.</p>

<h2>Interior surfaces</h2>
<ul>
<li>☐ Solid inner liners throughout; no exposed insulation and no perforated liners in the airstream except where acoustics require it and the owner accepts it with protected facing.</li>
<li>☐ Liner material resistant to the cleaning and disinfecting agents the owner will use. Stainless steel in wet sections; stainless or coated steel elsewhere as the owner requires. See <a href="<?= url('guides/casing-materials-galvanized-stainless-aluminum') ?>">casing materials</a>.</li>
<li>☐ Smooth interior with flush panel joints. Avoid exposed stiffeners, channels and ledges where dust settles.</li>
<li>☐ Fastener heads flush or covered; no exposed sheet metal screw tips inside.</li>
<li>☐ Interior panel joints sealed with a cleanable, durable sealant; no open crevices.</li>
<li>☐ Sealants and gaskets that do not support microbial growth and resist cleaning agents.</li>
<li>☐ Interior corners radiused or sealed so a cloth can reach them.</li>
</ul>

<h2>Floors</h2>
<ul>
<li>☐ Floors in wet sections continuously welded, sloped to drain and made of stainless steel. See <a href="<?= url('guides/drainable-welded-ahu-floors') ?>">welded and drainable floors</a>.</li>
<li>☐ Floors in dry sections smooth, sealed and strong enough for cleaning staff to walk on.</li>
<li>☐ Floor-to-wall junctions sealed or coved.</li>
<li>☐ No floor penetrations for supports; components mounted on welded pads or raised frames that can be cleaned under.</li>
<li>☐ Floor drains trapped and accessible, with traps that maintain a seal.</li>
</ul>

<h2>Drain pans</h2>
<ul>
<li>☐ Stainless steel, welded corners, sloped to a flush outlet so no water stands. See <a href="<?= url('guides/drain-pan-design-ashrae-62-1') ?>">drain pan design</a>.</li>
<li>☐ Pan visible and reachable for cleaning across its full area, including beneath the coil.</li>
<li>☐ Coil supports that do not create pockets in the pan.</li>
<li>☐ Removable coils, or coils raised enough above the pan to clean underneath.</li>
</ul>

<h2>Components</h2>
<ul>
<li>☐ Coils with fin spacing that can be cleaned; coil frames of stainless or coated material; coils removable or with access on both faces.</li>
<li>☐ Fans that can be inspected and cleaned, including the inlet and the wheel; fan arrays with removable fan modules.</li>
<li>☐ Motors and drives that do not shed belt dust into the airstream; direct-drive fans preferred.</li>
<li>☐ Humidifiers with absorption distance fully inside a welded, drained section, followed by nothing that can get wet.</li>
<li>☐ Dampers with blades and linkages that can be reached and wiped.</li>
<li>☐ Sound attenuators of packless design or with protected, cleanable fill in hygiene-critical units.</li>
<li>☐ Energy recovery devices with access on both airstreams for cleaning, and with documented cleaning methods.</li>
</ul>

<h2>Access and inspection</h2>
<ul>
<li>☐ Access doors upstream and downstream of every coil, humidifier, fan and energy recovery device. See the <a href="<?= url('guides/access-section-service-checklist') ?>">access section checklist</a>.</li>
<li>☐ Doors large enough to bring in cleaning equipment.</li>
<li>☐ View ports at coils, humidifiers and fans for inspection without opening.</li>
<li>☐ Interior lighting in all access sections.</li>
<li>☐ Access sections long enough to work inside comfortably.</li>
</ul>

<h2>Casing integrity</h2>
<ul>
<li>☐ Low leakage class so unfiltered air is not drawn into negative-pressure sections downstream of filters.</li>
<li>☐ Thermal bridging class high enough that interior surfaces in cold sections do not reach the dew point, and exterior surfaces do not sweat.</li>
<li>☐ Penetrations sealed on both faces with cleanable grommets.</li>
<li>☐ No insulation edges exposed at penetrations, doors or cut-outs.</li>
</ul>

<h2>Documentation and handover</h2>
<ul>
<li>☐ Materials list for all airstream surfaces, sealants and gaskets.</li>
<li>☐ Compatibility of surfaces with the owner's cleaning and disinfecting agents.</li>
<li>☐ Cleaning instructions for each component.</li>
<li>☐ Factory cleanliness on delivery: unit cleaned, openings sealed for shipping and storage, with protective caps on duct connections.</li>
<li>☐ Inspection at receipt and before start-up to confirm the interior is clean and dry.</li>
</ul>
<p class="note">Hygienic construction costs more than standard construction, mainly in stainless surfaces, welding and additional access. Prioritize wet sections and anything downstream of the final filters if budget limits the scope.</p>
<h2>Inspecting a hygienic unit in service</h2>
<ul>
<li>☐ Drain pans and wet floors dry within a short time after cooling stops.</li>
<li>☐ No visible biofilm, staining or odour in coil and humidifier sections.</li>
<li>☐ Sealants and gaskets intact, not cracked, peeling or discoloured.</li>
<li>☐ No new penetrations made since start-up without proper sealing.</li>
<li>☐ Liners free of dents, scratches and corrosion spots that trap dirt.</li>
<li>☐ Cleaning records kept for each section, with agents used.</li>
</ul>
<h2>Factory and site cleanliness</h2>
<p>A unit built to hygienic standards can still arrive dirty. Ask for interior cleaning before shipping, protective caps on every opening, and wrapping that keeps rain out during transport and storage. On site, keep the unit sealed until ductwork is connected, and do not run it as a construction ventilator without temporary filters. Inspect inside before start-up and clean again if construction dust has entered.</p>
